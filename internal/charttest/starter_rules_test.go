var update = flag.Bool("update", false, "rewrite the rendered starter rules and their promtool tests")

// ruleDir holds the Helm-rendered starter rules and their promtool tests,
// which task test runs with the pinned promtool (scripts/promtool.sh).
const ruleDir = "../../testdata/observability/rules"

// ruleReleases are the releases whose rendered rules the tests load: two
// releases with identical binding names must not see each other's series.
var ruleReleases = []string{"konstapel", "konstapel-b"}

// starterAlerts are the seven starter alerts of the design (task 5.1).
var starterAlerts = []string{
	"KonstapelMetricsUnavailable", "KonstapelObservationUnavailable", "KonstapelBindingUnresolved",
	"KonstapelEngineUnavailable", "KonstapelAssessmentOverdue", "KonstapelPublicationFailing", "KonstapelCleanupBlocked",
}

// starterValues enables the rules and the ServiceMonitor with every other
// value at its default: the rules an enabled default install renders.
const starterValues = "metrics:\n  enabled: true\n  serviceMonitor:\n    enabled: true\n  prometheusRule:\n    enabled: true\n"

func renderStarterRules(t *testing.T, release string, set ...string) map[string]any {
	t.Helper()
	args := []string{"template", release, "../../charts/konstapel", "--namespace", controllerNS, "--set", "image.digest=" + digest,
		"--api-versions", smAPI, "--api-versions", prAPI, "-f", "-"}
	for _, s := range set {
		args = append(args, "--set", s)
	}
	cmd := exec.Command("helm", args...)
	cmd.Stdin = strings.NewReader(starterValues)
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("render %s: %v\n%s", release, err, out)
	}
	_, pr := monitoringDocs(documents(t, out))
	if pr == nil {
		t.Fatalf("%s: an enabled default install rendered no PrometheusRule", release)
	}
	return pr
}

func goldenFile(t *testing.T, name string, got []byte) {
	t.Helper()
	path := filepath.Join(ruleDir, name)
	if *update {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil || !bytes.Equal(want, got) {
		t.Errorf("%s is stale; run go test ./internal/charttest -run TestStarterRules -update", path)
	}
}

// An enabled default install renders exactly the seven starter alerts,
// valid for the pinned Operator, each with a runbook in
// docs/integration/alert-runbooks.md. The rule files promtool checks and
// tests are these rendered objects' spec.groups, byte for byte.
func TestStarterRulesRendered(t *testing.T) {
	schema := prometheusRuleSchema(t)
	runbooks, err := os.ReadFile("../../docs/integration/alert-runbooks.md")
	if err != nil {
		t.Fatal(err)
	}
	for _, release := range ruleReleases {
		pr := renderStarterRules(t, release)
		schema.check(t, pr)
		var names []string
		for _, r := range rules(t, pr) {
			names = append(names, r.alert)
			if r.severity != "warning" || r.forDur == "" {
				t.Errorf("%s: severity %s, for %q", r.alert, r.severity, r.forDur)
			}
			anchor := "#" + strings.ToLower(r.alert)
			if r.runbook != "https://github.com/backend-bunny/Konstapel/blob/main/docs/integration/alert-runbooks.md"+anchor {
				t.Errorf("%s: runbook %s", r.alert, r.runbook)
			}
			if !strings.Contains(string(runbooks), "\n## "+r.alert+"\n") {
				t.Errorf("docs/integration/alert-runbooks.md has no section for %s", r.alert)
			}
			for _, bad := range []string{"__scope", "__threshold__", "__window__", "__owner"} {
				if strings.Contains(r.expr, bad) {
					t.Errorf("%s: unexpanded %s in %s", r.alert, bad, r.expr)
				}
			}
			// Release scope: every selector carries the release's exact
			// matchers, and nothing selects another release.
			want := fmt.Sprintf(`app_kubernetes_io_instance=%q,job="konstapel-controller-metrics",namespace="konstapel-system"`, release)
			if n, m := strings.Count(r.expr, "{"), strings.Count(r.expr, "{"+want); n == 0 || n != m {
				t.Errorf("%s: %d of %d selectors carry the release scope: %s", r.alert, m, n, r.expr)
			}
			// Binding and backlog gauges are never summed across replicas.
			if strings.Contains(r.expr, "sum") && !strings.Contains(r.expr, "sum by (app_kubernetes_io_instance, job, namespace) (increase(konstapel_operation_attempts_total") {
				t.Errorf("%s sums something other than attempt increases: %s", r.alert, r.expr)
			}
		}
		slices.Sort(names)
		want := slices.Sorted(slices.Values(starterAlerts))
		if !slices.Equal(names, want) {
			t.Errorf("%s: alerts %v, want %v", release, names, want)
		}
		raw, err := yaml.Marshal(map[string]any{"groups": at(pr, "spec", "groups")})
		if err != nil {
			t.Fatal(err)
		}
		header := fmt.Sprintf("# Generated by `go test ./internal/charttest -run TestStarterRules -update`:\n"+
			"# spec.groups of the PrometheusRule that `helm template %s charts/konstapel`\n"+
			"# renders with metrics, the ServiceMonitor and the PrometheusRule enabled.\n", release)
		goldenFile(t, release+".rules.yml", append([]byte(header), raw...))
	}
}

// Disabling the starter groups, or every rule, renders no PrometheusRule;
// tuning one starter rule changes only that rule.
func TestStarterRulesTuning(t *testing.T) {
	base := rules(t, renderStarterRules(t, "konstapel"))
	_, none := monitoringDocs(mustRender(t, []string{prAPI}, "metrics:\n  enabled: true\n  prometheusRule:\n    enabled: true\n",
		"metrics.prometheusRule.groups.konstapel-availability.enabled=false", "metrics.prometheusRule.groups.konstapel-operations.enabled=false"))
	if none != nil {
		t.Error("PrometheusRule rendered with both starter groups disabled")
	}
	p := "metrics.prometheusRule.groups.konstapel-operations.rules."
	tuned := rules(t, renderStarterRules(t, "konstapel", p+"KonstapelPublicationFailing.threshold=5", p+"KonstapelPublicationFailing.window=30m",
		p+"KonstapelPublicationFailing.for=4m", "metrics.prometheusRule.maxProjectionAge=5m"))
	for i, r := range tuned {
		if r.alert == "KonstapelPublicationFailing" && (!strings.Contains(r.expr, "[30m])) >= 5") || r.forDur != "4m") {
			t.Errorf("tuned %+v", r)
		}
		if strings.Contains(base[i].expr, "< 240") && (strings.Contains(r.expr, "< 240") || !strings.Contains(r.expr, "< 300")) {
			t.Errorf("%s: owner gate does not follow maxProjectionAge: %s", r.alert, r.expr)
		}
		// Apart from the gate, tuning one rule leaves the others alone.
		if r.alert != "KonstapelPublicationFailing" && r.expr != strings.ReplaceAll(base[i].expr, "< 240", "< 300") {
			t.Errorf("%s changed beyond its owner gate: %s", r.alert, r.expr)
		}
	}
	// External scrape jobs: the scope's labels drive aggregation and joins.
	ext := rules(t, renderStarterRules(t, "konstapel", "metrics.prometheusRule.scope.matchers.job=vm-konstapel", "metrics.prometheusRule.scope.matchers.cluster=prod"))
	for _, r := range ext {
		if strings.Contains(r.expr, "app_kubernetes_io_instance") || !strings.Contains(r.expr, `{cluster="prod",job="vm-konstapel"`) {
			t.Errorf("%s: external scope %s", r.alert, r.expr)
		}
		if strings.Contains(r.expr, " by (") && !strings.Contains(r.expr, " by (cluster, job") {
			t.Errorf("%s: aggregation does not keep the scope labels: %s", r.alert, r.expr)
		}
	}
	// The custom outcome rule documented in the runbooks renders with the
	// owner gate expanded.
	md, err := os.ReadFile("../../docs/integration/alert-runbooks.md")
	if err != nil {
		t.Fatal(err)
	}
	example := regexp.MustCompile("(?s)```yaml\n(metrics:.*?)```").FindStringSubmatch(string(md))
	if example == nil {
		t.Fatal("alert-runbooks.md has no custom rule example")
	}
	_, out, err := renderWith(t, []string{prAPI}, example[1], "metrics.enabled=true", "metrics.prometheusRule.enabled=true")
	if err != nil {
		t.Fatalf("custom rule example: %v\n%s", err, out)
	}
	_, pr := monitoringDocs(documents(t, []byte(out)))
	found := false
	for _, r := range rules(t, pr) {
		if r.alert == "MyBindingHasFailingChecks" {
			found = strings.Contains(r.expr, `domain="assessment"} == 1`) && strings.HasSuffix(r.expr, ") > 0") && !strings.Contains(r.expr, "__")
		}
	}
	if !found {
		t.Error("the documented custom rule did not render with its owner gate")
	}
	for _, c := range []struct{ name, set, want string }{
		{"window without value", p + "KonstapelPublicationFailing.window=null", "sets no window"},
		{"unknown owner domain", p + "KonstapelBindingUnresolved.expr=x and __owner(nope)__", "the domain must be"},
		{"projection age below the controller maximum", "metrics.prometheusRule.maxProjectionAge=2m", "maxProjectionAge"},
		{"projection age below maximum plus scrape interval", "metrics.prometheusRule.maxProjectionAge=140s", "maxProjectionAge"},
		{"scope on instance", "metrics.prometheusRule.scope.matchers.instance=a", "must not match instance"},
	} {
		_, out, err := renderWith(t, []string{smAPI, prAPI}, starterValues, c.set)
		if err == nil || !strings.Contains(out, c.want) {
			t.Errorf("%s: err %v, output %q lacks %q", c.name, err, out, c.want)
		}
	}
}

// ruleCases is a promtool rule-test file whose series name scrape targets
// (@target) and whose expected alerts name a release instead of spelling
// out its scope labels. Severity and annotations come from the rendered
// rules, so the generated test also checks the annotation templates.
type ruleCases struct {
	RuleFiles []string `json:"rule_files"`
	// Targets maps a target name to its release and pod.
	Targets map[string]struct {
		Release string `json:"release"`
		Pod     string `json:"pod"`
		IP      string `json:"ip"`
	} `json:"targets"`
	Tests []struct {
		Name        string `json:"name"`
		Interval    string `json:"interval"`
		InputSeries []struct {
			Series string `json:"series"`
			Values string `json:"values"`
		} `json:"input_series"`
		AlertRuleTest []struct {
			EvalTime  string              `json:"eval_time"`
			Alertname string              `json:"alertname"`
			ExpAlerts []map[string]string `json:"exp_alerts"`
		} `json:"alert_rule_test"`
	} `json:"tests"`
}

func scopeLabels(release string) map[string]string {
	return map[string]string{"app_kubernetes_io_instance": release, "job": "konstapel-controller-metrics", "namespace": controllerNS}
}

func renderLabels(m map[string]string) string {
	var parts []string
	for _, k := range slices.Sorted(func(yield func(string) bool) {
		for k := range m {
			if !yield(k) {
				return
			}
		}
	}) {
		parts = append(parts, fmt.Sprintf("%s=%q", k, m[k]))
	}
	return strings.Join(parts, ",")
}

var (
	seriesRE     = regexp.MustCompile(`^([a-zA-Z_:][a-zA-Z0-9_:]*)\{(.*)\}$`)
	labelRE      = regexp.MustCompile(`^([a-zA-Z_][a-zA-Z0-9_]*)="([^"]*)"$`)
	annotationRE = regexp.MustCompile(`\{\{ \$labels\.([a-z_]+) \}\}`)
)

// checkSeries verifies that a test's input series is one Konstapel exposes:
// up, or a catalog family with exactly its labels and enum values, on a
// ServiceMonitor target of a release.
func checkSeries(t *testing.T, series string, target map[string]string) {
	t.Helper()
	m := seriesRE.FindStringSubmatch(series)
	if m == nil {
		t.Errorf("series %q is not name{labels}", series)
		return
	}
	labels := map[string]string{}
	for _, l := range strings.Split(m[2], ",") {
		lm := labelRE.FindStringSubmatch(strings.TrimSpace(l))
		if lm == nil {
			t.Errorf("series %q: label %q", series, l)
			return
		}
		labels[lm[1]] = lm[2]
	}
	for k, v := range target {
		if labels[k] != v {
			t.Errorf("series %q lacks target label %s=%q", series, k, v)
		}
		delete(labels, k)
	}
	if m[1] == "up" {
		if len(labels) != 0 {
			t.Errorf("series %q: up has only target labels", series)
		}
		return
	}
	name := m[1]
	for _, suffix := range []string{"_count", "_sum", "_bucket"} {
		if base, ok := strings.CutSuffix(name, suffix); ok && strings.HasSuffix(base, "_seconds") {
			name = base
			delete(labels, "le")
		}
	}
	for _, metric := range observability.Catalog {
		if metric.Name != name {
			continue
		}
		for _, l := range metric.Labels {
			v, ok := labels[l.Name]
			if !ok || (l.Values != nil && !slices.Contains(l.Values, v)) {
				t.Errorf("series %q: label %s=%q is not in the catalog", series, l.Name, v)
			}
			delete(labels, l.Name)
		}
		if len(labels) != 0 {
			t.Errorf("series %q: labels %v are not in the catalog", series, labels)
		}
		return
	}
	t.Errorf("series %q: %s is not a catalog family", series, name)
}

// The rule tests are generated from compact cases: series must be
// families the catalog defines on a release's scrape targets, and every
// starter alert must be exercised.
func TestStarterRuleTests(t *testing.T) {
	ruleFiles := map[string][]any{}
	for _, release := range ruleReleases {
		var doc struct {
			Groups []any `json:"groups"`
		}
		raw, err := os.ReadFile(filepath.Join(ruleDir, release+".rules.yml"))
		if err != nil {
			t.Fatal(err)
		}
		if err := yaml.Unmarshal(raw, &doc); err != nil {
			t.Fatal(err)
		}
		ruleFiles[release+".rules.yml"] = doc.Groups
	}
	cases, err := filepath.Glob(filepath.Join(ruleDir, "*.cases.yaml"))
	if err != nil || len(cases) == 0 {
		t.Fatalf("no rule cases: %v", err)
	}
	exercised := map[string]bool{}
	for _, file := range cases {
		raw, err := os.ReadFile(file)
		if err != nil {
			t.Fatal(err)
		}
		var c ruleCases
		if err := yaml.UnmarshalStrict(raw, &c); err != nil {
			t.Fatalf("%s: %v", file, err)
		}
		// Alert definitions by name in this file's rule files.
		defs := map[string][]map[string]any{}
		for _, rf := range c.RuleFiles {
			groups, ok := ruleFiles[rf]
			if !ok {
				t.Fatalf("%s: unknown rule file %s", file, rf)
			}
			for _, g := range groups {
				for _, r := range g.(map[string]any)["rules"].([]any) {
					r := r.(map[string]any)
					defs[fmt.Sprint(r["alert"])] = append(defs[fmt.Sprint(r["alert"])], r)
				}
			}
		}
		targets := map[string]map[string]string{}
		for name, tg := range c.Targets {
			l := scopeLabels(tg.Release)
			l["pod"], l["instance"], l["container"], l["endpoint"], l["service"] = tg.Pod, tg.IP+":8443", "controller", "https", "konstapel-controller-metrics"
			targets[name] = l
		}
		var tests []any
		for _, tc := range c.Tests {
			var series []any
			for _, s := range tc.InputSeries {
				name, rest, ok := strings.Cut(s.Series, "{@")
				if !ok {
					t.Errorf("%s/%s: series %q names no target", file, tc.Name, s.Series)
					continue
				}
				tname, extra, _ := strings.Cut(strings.TrimSuffix(rest, "}"), ",")
				target, ok := targets[tname]
				if !ok {
					t.Errorf("%s/%s: unknown target %s", file, tc.Name, tname)
					continue
				}
				full := name + "{" + renderLabels(target)
				if extra != "" {
					full += "," + extra
				}
				full += "}"
				checkSeries(t, full, target)
				series = append(series, map[string]any{"series": full, "values": s.Values})
			}
			var alertTests []any
			for _, art := range tc.AlertRuleTest {
				rs := defs[art.Alertname]
				if len(rs) == 0 {
					t.Errorf("%s/%s: no rule %s", file, tc.Name, art.Alertname)
					continue
				}
				exercised[art.Alertname] = exercised[art.Alertname] || len(art.ExpAlerts) > 0
				exp := []any{}
				for _, want := range art.ExpAlerts {
					labels := map[string]string{}
					for k, v := range want {
						if k == "release" {
							for sk, sv := range scopeLabels(v) {
								labels[sk] = sv
							}
							continue
						}
						labels[k] = v
					}
					r := rs[0]
					labels["severity"] = fmt.Sprint(r["labels"].(map[string]any)["severity"])
					annotations := map[string]string{}
					for k, v := range r["annotations"].(map[string]any) {
						s := annotationRE.ReplaceAllStringFunc(fmt.Sprint(v), func(m string) string {
							return labels[annotationRE.FindStringSubmatch(m)[1]]
						})
						if strings.Contains(s, "{{") {
							t.Errorf("%s: annotation %s uses a template other than {{ $labels.<name> }}: %s", art.Alertname, k, v)
						}
						annotations[k] = s
					}
					exp = append(exp, map[string]any{"exp_labels": labels, "exp_annotations": annotations})
				}
				alertTests = append(alertTests, map[string]any{"eval_time": art.EvalTime, "alertname": art.Alertname, "exp_alerts": exp})
			}
			tests = append(tests, map[string]any{"name": tc.Name, "interval": tc.Interval, "input_series": series, "alert_rule_test": alertTests})
		}
		out, err := yaml.Marshal(map[string]any{"rule_files": c.RuleFiles, "evaluation_interval": "1m", "tests": tests})
		if err != nil {
			t.Fatal(err)
		}
		base := strings.TrimSuffix(filepath.Base(file), ".cases.yaml")
		header := fmt.Sprintf("# Generated by `go test ./internal/charttest -run TestStarterRules -update` from\n# %s.cases.yaml and the rendered rules; run with promtool test rules.\n", base)
		goldenFile(t, base+".test.yml", append([]byte(header), out...))
	}
	for _, a := range starterAlerts {
		if !exercised[a] {
			t.Errorf("no rule test expects %s to fire", a)
		}
	}
}
