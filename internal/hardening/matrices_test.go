// Per-check CLI matrices (tasks 2.3-2.5). Every case's expected result comes
// from a small Go model of the intended semantics below, written
// independently of the policy expressions; the generated kyverno tests then
// require the shipped variant to agree with the model on every case.

// A case places one subject container of a class (regular, init or
// ephemeral) in a workload form, next to a compliant regular container when
// the subject is not itself the regular container.
type matrixCase struct {
	name      string
	form      string // Pod, Deployment or CronJob
	class     string // regular, init or ephemeral
	windows   bool
	podSC     map[string]any // Pod-level securityContext (nil: unset)
	subjectSC map[string]any // the subject container's securityContext (nil: unset)
	want      bool           // model: true passes
}

var classes = []string{"regular", "init", "ephemeral"}

// formsFor lists where a class applies: ephemeral containers exist only on
// Pods (added through the ephemeralcontainers subresource).
func formsFor(class string) []string {
	if class == "ephemeral" {
		return []string{"Pod"}
	}
	return []string{"Pod", "Deployment", "CronJob"}
}

// otherSC is the securityContext of the companion container; it satisfies the
// check under test without relying on the Pod level.
type matrix struct {
	dir, check, prefix string
	otherSC            func() map[string]any
	cases              []matrixCase
}

func (m matrix) object(c matrixCase) map[string]any {
	ctr := func(name string, sc map[string]any) map[string]any {
		o := map[string]any{"name": name, "image": "busybox:1.38.0"}
		if sc != nil {
			o["securityContext"] = sc
		}
		return o
	}
	spec := map[string]any{}
	switch c.class {
	case "regular":
		spec["containers"] = []any{ctr("subject", c.subjectSC)}
	case "init":
		spec["containers"] = []any{ctr("app", m.otherSC())}
		spec["initContainers"] = []any{ctr("subject", c.subjectSC)}
	case "ephemeral":
		spec["containers"] = []any{ctr("app", m.otherSC())}
		spec["ephemeralContainers"] = []any{ctr("subject", c.subjectSC)}
	}
	if c.podSC != nil {
		spec["securityContext"] = c.podSC
	}
	if c.windows {
		spec["os"] = map[string]any{"name": "windows"}
	}
	obj := map[string]any{"metadata": map[string]any{"name": c.name, "namespace": "default"}}
	switch c.form {
	case "Pod":
		obj["apiVersion"], obj["kind"], obj["spec"] = "v1", "Pod", spec
	case "Deployment":
		obj["apiVersion"], obj["kind"], obj["spec"] = "apps/v1", "Deployment", template(spec)
	case "CronJob":
		obj["apiVersion"], obj["kind"] = "batch/v1", "CronJob"
		obj["spec"] = map[string]any{"schedule": "0 * * * *", "jobTemplate": map[string]any{"spec": map[string]any{"template": map[string]any{"spec": withRestart(spec)}}}}
	}
	return obj
}

func (m matrix) generate() (resources, test []byte) {
	header := []byte(fmt.Sprintf("# Generated by internal/hardening (go test ./internal/hardening -run TestCheckMatrices -update). Do not edit.\n# %s: expected results come from the Go model in matrices_test.go.\n", m.check))
	var docs [][]byte
	type key struct{ kind, result string }
	grouped := map[key][]string{}
	var keys []key
	for _, c := range m.cases {
		b, _ := yaml.Marshal(m.object(c))
		docs = append(docs, b)
		k := key{c.form, map[bool]string{true: "pass", false: "fail"}[c.want]}
		if _, ok := grouped[k]; !ok {
			keys = append(keys, k)
		}
		grouped[k] = append(grouped[k], c.name)
	}
	var results []any
	for _, k := range keys {
		results = append(results, map[string]any{"isValidatingPolicy": true, "kind": k.kind, "policy": m.check, "result": k.result, "resources": grouped[k]})
	}
	t, _ := yaml.Marshal(map[string]any{"apiVersion": "cli.kyverno.io/v1alpha1", "kind": "Test", "metadata": map[string]any{"name": "linux-hardening-" + m.prefix},
		"policies": []any{"../../../content/linux-hardening/variants/" + m.check + ".yaml"}, "resources": []any{"resources.yaml"}, "results": results})
	return append(header, bytes.Join(docs, []byte("---\n"))...), append(header, t...)
}

func name(parts ...string) string {
	s := strings.ToLower(strings.Join(parts, "-"))
	s = strings.NewReplacer("_", "", " ", "-").Replace(s)
	return s
}

// --- 2.3 privilege escalation: only an explicit false passes; there is no
// Pod-level field, so nothing is inherited.

func escalationMatrix() matrix {
	m := matrix{dir: "escalation", check: "disallow-privilege-escalation", prefix: "escalation",
		otherSC: func() map[string]any { return map[string]any{"allowPrivilegeEscalation": false} }}
	values := []struct {
		label string
		sc    map[string]any
		want  bool
	}{
		{"false", map[string]any{"allowPrivilegeEscalation": false}, true},
		{"true", map[string]any{"allowPrivilegeEscalation": true}, false},
		{"missing", map[string]any{"privileged": false}, false},
		{"nocontext", nil, false},
	}
	for _, class := range classes {
		for _, form := range formsFor(class) {
			for _, v := range values {
				m.cases = append(m.cases, matrixCase{name: name("esc", form, class, v.label), form: form, class: class, subjectSC: v.sc, want: v.want})
			}
			// A Pod-level value (not a real PodSecurityContext field) is not inherited.
			m.cases = append(m.cases, matrixCase{name: name("esc", form, class, "podlevel-only"), form: form, class: class,
				podSC: map[string]any{"allowPrivilegeEscalation": false, "runAsNonRoot": true}, want: false})
			m.cases = append(m.cases, matrixCase{name: name("esc", form, class, "windows-true"), form: form, class: class, windows: true,
				subjectSC: map[string]any{"allowPrivilegeEscalation": true}, want: true})
		}
	}
	return m
}

// --- 2.4 capabilities: drop must contain the exact string ALL, and every
// added capability must be exactly NET_BIND_SERVICE. Both validations of the
// combined shipped policy apply.

func capabilitiesModel(drop, add []string) bool {
	return slices.Contains(drop, "ALL") && !slices.ContainsFunc(add, func(c string) bool { return c != "NET_BIND_SERVICE" })
}

func capabilitiesMatrix() matrix {
	m := matrix{dir: "capabilities", check: "disallow-capabilities-strict", prefix: "capabilities",
		otherSC: func() map[string]any { return map[string]any{"capabilities": map[string]any{"drop": []any{"ALL"}}} }}
	drops := []struct {
		label string
		v     []string
	}{{"all", []string{"ALL"}}, {"lower", []string{"all"}}, {"netraw", []string{"NET_RAW"}}, {"all-and-netraw", []string{"NET_RAW", "ALL"}}, {"empty", []string{}}, {"none", nil}}
	adds := []struct {
		label string
		v     []string
	}{{"none", nil}, {"empty", []string{}}, {"nbs", []string{"NET_BIND_SERVICE"}}, {"nbs-lower", []string{"net_bind_service"}}, {"sysadmin", []string{"SYS_ADMIN"}}, {"nbs-sysadmin", []string{"NET_BIND_SERVICE", "SYS_ADMIN"}}}
	toAny := func(v []string) []any {
		out := []any{}
		for _, s := range v {
			out = append(out, s)
		}
		return out
	}
	for _, class := range classes {
		for _, form := range formsFor(class) {
			for _, d := range drops {
				for _, a := range adds {
					caps := map[string]any{}
					if d.v != nil {
						caps["drop"] = toAny(d.v)
					}
					if a.v != nil {
						caps["add"] = toAny(a.v)
					}
					m.cases = append(m.cases, matrixCase{name: name("cap", form, class, "drop", d.label, "add", a.label), form: form, class: class,
						subjectSC: map[string]any{"capabilities": caps}, want: capabilitiesModel(d.v, a.v)})
				}
			}
			m.cases = append(m.cases, matrixCase{name: name("cap", form, class, "nocontext"), form: form, class: class, want: false})
			m.cases = append(m.cases, matrixCase{name: name("cap", form, class, "windows-sysadmin"), form: form, class: class, windows: true,
				subjectSC: map[string]any{"capabilities": map[string]any{"add": []any{"SYS_ADMIN"}}}, want: true})
		}
	}
	return m
}

// --- 2.5 seccomp: a Pod-level type, if set, must be allowed; each container
// must set an allowed type or, when it sets none, inherit an allowed Pod
// type. Allowed types are exactly RuntimeDefault and Localhost.

var seccompTypes = []string{"", "RuntimeDefault", "Localhost", "Unconfined"}

func seccompAllowed(t string) bool { return t == "RuntimeDefault" || t == "Localhost" }

func seccompModel(pod, ctr string) bool {
	if pod != "" && !seccompAllowed(pod) {
		return false
	}
	if ctr != "" {
		return seccompAllowed(ctr)
	}
	return seccompAllowed(pod)
}

func seccompProfile(t string) map[string]any {
	p := map[string]any{"type": t}
	if t == "Localhost" {
		p["localhostProfile"] = "profiles/audit.json"
	}
	return p
}

func seccompMatrix() matrix {
	m := matrix{dir: "seccomp", check: "restrict-seccomp-strict", prefix: "seccomp",
		otherSC: func() map[string]any { return map[string]any{"seccompProfile": seccompProfile("RuntimeDefault")} }}
	label := func(t string) string {
		if t == "" {
			return "unset"
		}
		return t
	}
	for _, class := range classes {
		for _, form := range formsFor(class) {
			for _, pod := range seccompTypes {
				for _, ctr := range seccompTypes {
					c := matrixCase{name: name("sec", form, class, "pod", label(pod), "ctr", label(ctr)), form: form, class: class, want: seccompModel(pod, ctr)}
					if pod != "" {
						c.podSC = map[string]any{"seccompProfile": seccompProfile(pod)}
					}
					if ctr != "" {
						c.subjectSC = map[string]any{"seccompProfile": seccompProfile(ctr)}
					}
					m.cases = append(m.cases, c)
				}
			}
			m.cases = append(m.cases, matrixCase{name: name("sec", form, class, "windows-unconfined"), form: form, class: class, windows: true,
				podSC: map[string]any{"seccompProfile": seccompProfile("Unconfined")}, subjectSC: map[string]any{"seccompProfile": seccompProfile("Unconfined")}, want: true})
		}
	}
	return m
}

func TestCheckMatrices(t *testing.T) {
	for _, m := range []matrix{escalationMatrix(), capabilitiesMatrix(), seccompMatrix()} {
		t.Run(m.dir, func(t *testing.T) {
			resources, test := m.generate()
			dir := filepath.Join(root, "testdata/linux-hardening", m.dir)
			for file, want := range map[string][]byte{"resources.yaml": resources, "kyverno-test.yaml": test} {
				path := filepath.Join(dir, file)
				if *update {
					if err := os.MkdirAll(dir, 0o755); err != nil {
						t.Fatal(err)
					}
					if err := os.WriteFile(path, want, 0o644); err != nil {
						t.Fatal(err)
					}
					continue
				}
				if got, err := os.ReadFile(path); err != nil || !bytes.Equal(got, want) {
					t.Errorf("%s is stale; run go test ./internal/hardening -run TestCheckMatrices -update", path)
				}
			}
			// Names are unique and DNS-safe, and both outcomes occur for every
			// class and form.
			seen := map[string]bool{}
			outcomes := map[string]map[bool]bool{}
			for _, c := range m.cases {
				if seen[c.name] || len(c.name) > 63 || strings.ContainsAny(c.name, "_ ABCDEFGHIJKLMNOPQRSTUVWXYZ") {
					t.Errorf("bad or duplicate name %q", c.name)
				}
				seen[c.name] = true
				k := c.form + "/" + c.class
				if outcomes[k] == nil {
					outcomes[k] = map[bool]bool{}
				}
				outcomes[k][c.want] = true
			}
			for k, o := range outcomes {
				if !o[true] || !o[false] {
					t.Errorf("%s: only one outcome in %s", m.check, k)
				}
			}
		})
	}
}

// The models themselves encode the spec's stated cases.
func TestMatrixModelsMatchTheSpec(t *testing.T) {
	// "An allowed capability is added without dropping defaults" is rejected.
	if capabilitiesModel(nil, []string{"NET_BIND_SERVICE"}) {
		t.Error("NET_BIND_SERVICE without drop ALL passed")
	}
	if !capabilitiesModel([]string{"ALL"}, []string{"NET_BIND_SERVICE"}) || capabilitiesModel([]string{"all"}, nil) || capabilitiesModel([]string{"ALL"}, []string{"net_bind_service"}) {
		t.Error("capabilities model is case-insensitive or rejects the permitted addition")
	}
	// "No seccomp profile can be inherited" is rejected; an invalid Pod type
	// fails even when the container overrides it.
	if seccompModel("", "") || seccompModel("Unconfined", "RuntimeDefault") || !seccompModel("Localhost", "") || seccompModel("RuntimeDefault", "Unconfined") {
		t.Error("seccomp model")
	}
}
