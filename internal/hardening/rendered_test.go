// Task 4.1: the four checks rendered as binding instances, Audit everywhere
// and Deny in production, are golden files and the input of a generated
// Kyverno CLI test. go test ./internal/hardening -run TestRenderedBundleFixtures -update
// regenerates both (the rendered names derive from the bundle digest).

var hardeningChecks = []string{"disallow-capabilities-strict", "disallow-privilege-escalation", "require-run-as-nonroot", "restrict-seccomp-strict"}

var bundleBindings = []struct {
	name string
	mode v1alpha1.EnforcementMode
	sel  v1alpha1.NamespaceSelector
	in   []string // namespaces the selector must select
}{
	{"audit-all", v1alpha1.ModeAudit, v1alpha1.NamespaceSelector{}, []string{"shop-dev", "shop-prod"}},
	{"deny-production", v1alpha1.ModeDeny, v1alpha1.NamespaceSelector{MatchLabels: map[string]v1alpha1.LabelValue{"environment": "production"}}, []string{"shop-prod"}},
}

var bundleNamespaces = map[string]labels.Set{"shop-prod": {"environment": "production"}, "shop-dev": {"environment": "development"}}

type renderedInstance struct {
	binding, check string
	obj            *unstructured.Unstructured
}

func renderBundle(t *testing.T) []renderedInstance {
	t.Helper()
	c, ref := served(t)
	var policies []v1alpha1.ProfilePolicy
	for _, name := range hardeningChecks {
		policies = append(policies, v1alpha1.ProfilePolicy{Name: name})
	}
	profile := v1alpha1.ComplianceProfile{ObjectMeta: metav1.ObjectMeta{Name: "linux-hardening", UID: "p-hardening", Generation: 1},
		Spec: v1alpha1.ComplianceProfileSpec{Bundle: ref, Policies: policies}}
	var bindings []v1alpha1.ComplianceBinding
	for _, b := range bundleBindings {
		sel := b.sel
		bindings = append(bindings, v1alpha1.ComplianceBinding{ObjectMeta: metav1.ObjectMeta{Name: b.name, UID: k8stypes.UID("uid-" + b.name), Generation: 1},
			Spec: v1alpha1.ComplianceBindingSpec{ProfileRef: v1alpha1.ProfileReference{Name: profile.Name}, Mode: b.mode, NamespaceSelector: &sel, EnforcementEpoch: 1}})
	}
	res := targeting.Resolve(targeting.Input{Cluster: "kube-system:fixture", Bundles: []targeting.Bundle{c.Bundle},
		Profiles: []v1alpha1.ComplianceProfile{profile}, Bindings: bindings})
	var out []renderedInstance
	for _, br := range res.Bindings {
		if len(br.Errors) > 0 || len(br.Contributions) != len(hardeningChecks) {
			t.Fatalf("binding %s: %+v", br.Binding.Name, br)
		}
		for _, contrib := range br.Contributions {
			obj, err := targeting.Render(contrib, c.Policies[contrib.Policy])
			if err != nil {
				t.Fatal(err)
			}
			out = append(out, renderedInstance{br.Binding.Name, contrib.Policy, obj})
		}
	}
	slices.SortFunc(out, func(a, b renderedInstance) int { return strings.Compare(a.binding+a.check, b.binding+b.check) })
	return out
}

// The workloads: per namespace, one compliant Pod, one Pod per violated
// check, and a CronJob template violating all four.
func bundleWorkloads() (docs [][]byte, violates map[string]string) {
	violates = map[string]string{} // workload -> violated check ("" = compliant, "*" = all)
	for _, ns := range []string{"shop-prod", "shop-dev"} {
		mk := func(name string, mutate func(sc map[string]any), cron bool) {
			ctr := compliantContainer()
			if mutate != nil {
				mutate(ctr["securityContext"].(map[string]any))
			}
			spec := map[string]any{"containers": []any{ctr}}
			obj := map[string]any{"apiVersion": "v1", "kind": "Pod", "metadata": map[string]any{"name": name, "namespace": ns}, "spec": spec}
			if cron {
				obj = map[string]any{"apiVersion": "batch/v1", "kind": "CronJob", "metadata": map[string]any{"name": name, "namespace": ns},
					"spec": map[string]any{"schedule": "0 * * * *", "jobTemplate": map[string]any{"spec": map[string]any{"template": map[string]any{"spec": withRestart(spec)}}}}}
			}
			b, _ := yaml.Marshal(obj)
			docs = append(docs, b)
		}
		mk("compliant", nil, false)
		violates[ns+"/compliant"] = ""
		for _, v := range violations {
			mk("violates-"+v.name, v.apply, false)
			violates[ns+"/violates-"+v.name] = v.check
		}
		mk("cronjob-violates-all", func(sc map[string]any) {
			for _, v := range violations {
				v.apply(sc)
			}
		}, true)
		violates[ns+"/cronjob-violates-all"] = "*"
	}
	return docs, violates
}

func renderedFiles(t *testing.T) map[string][]byte {
	t.Helper()
	header := "# Generated by internal/hardening (go test ./internal/hardening -run TestRenderedBundleFixtures -update). Do not edit.\n"
	files := map[string][]byte{}
	instances := renderBundle(t)
	var policyFiles []any
	for _, in := range instances {
		b, err := yaml.Marshal(in.obj.Object)
		if err != nil {
			t.Fatal(err)
		}
		name := in.binding + "-" + in.check + ".yaml"
		files[name] = append([]byte(header), b...)
		policyFiles = append(policyFiles, name)
	}
	docs, violates := bundleWorkloads()
	files["resources.yaml"] = append([]byte(header), bytes.Join(docs, []byte("---\n"))...)
	var nsSel []any
	for _, ns := range []string{"shop-prod", "shop-dev"} {
		nsSel = append(nsSel, map[string]any{"name": ns, "labels": map[string]any(map[string]any{"environment": bundleNamespaces[ns]["environment"]})})
	}
	values, _ := yaml.Marshal(map[string]any{"apiVersion": "cli.kyverno.io/v1alpha1", "kind": "Value", "namespaceSelector": nsSel})
	files["values.yaml"] = append([]byte(header), values...)

	// Expected results: a namespace outside a binding's selector is skipped;
	// inside it, each check fails only workloads violating it.
	type key struct{ policy, kind, result string }
	grouped := map[key][]string{}
	var keys []key
	workloads := make([]string, 0, len(violates))
	for w := range violates {
		workloads = append(workloads, w)
	}
	slices.Sort(workloads)
	for _, in := range instances {
		var selected []string
		for _, b := range bundleBindings {
			if b.name == in.binding {
				selected = b.in
			}
		}
		for _, w := range workloads {
			ns := strings.Split(w, "/")[0]
			kind := "Pod"
			if strings.Contains(w, "cronjob") {
				kind = "CronJob"
			}
			result := "pass"
			switch {
			case !slices.Contains(selected, ns):
				result = "skip"
			case violates[w] == "*" || violates[w] == in.check:
				result = "fail"
			}
			k := key{in.obj.GetName(), kind, result}
			if _, ok := grouped[k]; !ok {
				keys = append(keys, k)
			}
			grouped[k] = append(grouped[k], w)
		}
	}
	var results []any
	for _, k := range keys {
		results = append(results, map[string]any{"isValidatingPolicy": true, "policy": k.policy, "kind": k.kind, "result": k.result, "resources": grouped[k]})
	}
	test, _ := yaml.Marshal(map[string]any{"apiVersion": "cli.kyverno.io/v1alpha1", "kind": "Test", "metadata": map[string]any{"name": "linux-hardening-rendered"},
		"policies": policyFiles, "resources": []any{"resources.yaml"}, "variables": "values.yaml", "results": results})
	files["kyverno-test.yaml"] = append([]byte(header+"# Limitation of kyverno test 1.19: a selector-excluded resource passes any expected result; TestRenderedBundleInstances checks selectors in Go.\n"), test...)
	return files
}

func TestRenderedBundleFixtures(t *testing.T) {
	dir := filepath.Join(root, "testdata/linux-hardening/rendered")
	files := renderedFiles(t)
	if *update {
		if err := os.RemoveAll(dir); err != nil {
			t.Fatal(err)
		}
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	for name, want := range files {
		path := filepath.Join(dir, name)
		if *update {
			if err := os.WriteFile(path, want, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		if got, err := os.ReadFile(path); err != nil || !bytes.Equal(got, want) {
			t.Errorf("%s is stale; run go test ./internal/hardening -run TestRenderedBundleFixtures -update", path)
		}
	}
	if !*update {
		entries, _ := os.ReadDir(dir)
		if len(entries) != len(files) {
			t.Errorf("%s has %d files, generated %d", dir, len(entries), len(files))
		}
	}
}

// Every rendered instance is a v1 ValidatingPolicy with background
// evaluation, the binding's mode, revision and source provenance, the
// variant's unchanged resource rules and no exclusions, and a namespace
// selector that selects exactly the binding's namespaces.
func TestRenderedBundleInstances(t *testing.T) {
	c, _ := served(t)
	for _, in := range renderBundle(t) {
		o := in.obj.Object
		name := in.binding + "/" + in.check
		if o["apiVersion"] != "policies.kyverno.io/v1" || o["kind"] != "ValidatingPolicy" {
			t.Errorf("%s: %v %v", name, o["apiVersion"], o["kind"])
		}
		spec := o["spec"].(map[string]any)
		if bg, _, _ := unstructured.NestedBool(o, "spec", "evaluation", "background", "enabled"); !bg {
			t.Errorf("%s: background evaluation disabled", name)
		}
		var want *struct {
			name string
			mode v1alpha1.EnforcementMode
			sel  v1alpha1.NamespaceSelector
			in   []string
		}
		for i := range bundleBindings {
			if bundleBindings[i].name == in.binding {
				want = &bundleBindings[i]
			}
		}
		if !reflect.DeepEqual(spec["validationActions"], []any{string(want.mode)}) {
			t.Errorf("%s: actions %v", name, spec["validationActions"])
		}
		ann := in.obj.GetAnnotations()
		if ann[targeting.AnnotationRevision] == "" || ann[targeting.AnnotationSourceDigest] != c.Policies[in.check].SourceDigest || ann[targeting.AnnotationPolicy] != in.check {
			t.Errorf("%s: provenance %v", name, ann)
		}
		mc := spec["matchConstraints"].(map[string]any)
		for k := range mc {
			if k != "resourceRules" && k != "namespaceSelector" {
				t.Errorf("%s: unexpected matchConstraints.%s (hidden exclusion?)", name, k)
			}
		}
		if _, ok := spec["matchConditions"]; ok {
			t.Errorf("%s: matchConditions added", name)
		}
		src := jsonRoundTrip(t, c.Policies[in.check].Manifest)["spec"].(map[string]any)["matchConstraints"].(map[string]any)["resourceRules"]
		if !reflect.DeepEqual(jsonRoundTrip(t, spec)["matchConstraints"].(map[string]any)["resourceRules"], src) {
			t.Errorf("%s: resource rules differ from the variant", name)
		}
		raw, _, _ := unstructured.NestedMap(o, "spec", "matchConstraints", "namespaceSelector")
		var ls metav1.LabelSelector
		if err := runtime.DefaultUnstructuredConverter.FromUnstructured(raw, &ls); err != nil {
			t.Fatal(err)
		}
		sel, err := metav1.LabelSelectorAsSelector(&ls)
		if err != nil {
			t.Fatal(err)
		}
		var got []string
		for ns, l := range bundleNamespaces {
			if sel.Matches(l) {
				got = append(got, ns)
			}
		}
		slices.Sort(got)
		if !slices.Equal(got, want.in) {
			t.Errorf("%s selects %v, want %v", name, got, want.in)
		}
	}
}
