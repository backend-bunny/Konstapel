#!/usr/bin/env bash
# Copy the shipped controller RBAC, role catalog, and admission policies into
# the runtime chart unchanged: scripts/charts/runtime.sh OUT_DIR. They are the
# owners' generated or reviewed manifests (config/rbac, config/admission) for
# the konstapel-system namespace and konstapel-controller ServiceAccount, so
# the chart cannot drift from them. scripts/generate.sh runs this and, with
# --check, verifies the chart is current.
set -euo pipefail
cd "$(dirname "$0")/../.."
out=${1:?usage: runtime.sh OUT_DIR}
mkdir -p "$out"
find "$out" -maxdepth 1 -name 'generated-*.yaml' -delete
copy() { # SOURCE NAME
  { echo "# Generated by scripts/charts/runtime.sh from $1; do not edit."; cat "$1"; } > "$out/generated-$2.yaml"
}
copy config/rbac/controller/role.yaml controller-role
for f in config/rbac/*.yaml; do copy "$f" "rbac-$(basename "$f" .yaml)"; done
for f in config/admission/*.yaml; do copy "$f" "admission-$(basename "$f" .yaml)"; done
