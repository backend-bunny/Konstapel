#!/usr/bin/env bash
# Copy the shipped controller RBAC, role catalog, and admission policies into
# the runtime chart unchanged: scripts/charts/runtime.sh OUT_DIR. They are the
# owners' generated or reviewed manifests (config/rbac, config/admission) for
# the konstapel-system namespace and konstapel-controller ServiceAccount, so
# the chart cannot drift from them. scripts/generate.sh runs this and, with
# --check, verifies the chart is current.
#
# Two opt-in manifests are copied unchanged too, but wrapped so they render
# only with their chart switch (docs/charts.md, "Exception admission
# webhooks"): the gated revocation ClusterRole, inside an `if`, and the
# exception webhook configurations, inside a named template that
# exception-webhooks.yaml renders with the deployment's CA injection.
set -euo pipefail
cd "$(dirname "$0")/../.."
out=${1:?usage: runtime.sh OUT_DIR}
mkdir -p "$out"
find "$out" -maxdepth 1 -name 'generated-*.yaml' -delete
copy() { # SOURCE NAME
  { echo "# Generated by scripts/charts/runtime.sh from $1; do not edit."; cat "$1"; } > "$out/generated-$2.yaml"
}
# A wrapped manifest must not contain template syntax of its own.
plain() {
  if grep -q '{{' "$1"; then echo "$1 contains template syntax and cannot be copied unchanged" >&2; exit 1; fi
}
# Their header is a template comment, so a disabled switch renders nothing,
# not even a comment-only document.
gated() { # SOURCE NAME CONDITION
  plain "$1"
  { echo "{{- /* Generated by scripts/charts/runtime.sh from $1; do not edit. Rendered only when $3. */ -}}"
    echo "{{- if $3 }}"; cat "$1"; echo "{{- end }}"; } > "$out/generated-$2.yaml"
}
defined() { # SOURCE NAME TEMPLATE
  plain "$1"
  { echo "{{- /* Generated by scripts/charts/runtime.sh from $1; do not edit. The named template $3 holds the manifest; this file renders nothing. */ -}}"
    echo "{{- define \"$3\" }}"; cat "$1"; echo "{{- end }}"; } > "$out/generated-$2.yaml"
}
copy config/rbac/controller/role.yaml controller-role
gated config/rbac/controller/exception-revocation.yaml controller-exception-revocation .Values.exceptions.revocationProcessing.enabled
defined config/webhook/exceptions.yaml webhook-exceptions konstapel.generated.exceptionWebhooks
for f in config/rbac/*.yaml; do copy "$f" "rbac-$(basename "$f" .yaml)"; done
for f in config/admission/*.yaml; do copy "$f" "admission-$(basename "$f" .yaml)"; done
